"""Staff codes typed by an admin, and what happens when one changes.

The code was generated by the platform until 2026-09-21; now it is typed
on the Users form. Two consequences, and the second is the one worth
testing hard.

A typed value can be wrong -- blank, a duplicate, the same code in
different case -- and each of those failures surfaces days later, to a
staff member who cannot register and has no idea why. So they are
refused here, with a message against the field.

Note the codes used below: TST-A, TST-B. Deliberately NOT of the form
STF-000015, because the model still generates STF-<primary key> for
accounts made outside the form -- including the admin each of these tests
creates -- and primary keys climb across a test class. A hardcoded
STF-000015 eventually collides with a generated one and the test fails
for a reason that has nothing to do with what it is testing. (That
collision being refused is correct behaviour, and is now tested on
purpose rather than by accident.)

And a typed value can be CHANGED. Conecto gates registration on the code,
so changing one means the old code must be revoked or Conecto is left
holding two valid codes for one person. The stale one is the dangerous
half: nothing in this platform refers to it any more, so nothing here
will ever revoke it again. That is the shape of an ex-employee keeping
access, and most of what follows exists to pin it shut.
"""
from unittest.mock import patch

from django.contrib.auth import get_user_model
from django.test import TestCase, override_settings
from rest_framework.test import APIClient

from accounts.testing import ALL_SECTIONS

from .models import ConectoCall

User = get_user_model()

TOKEN = "test-shared-secret"

URLS = {"registerStaffCode": "https://example.invalid/registerStaffCode"}

CONFIGURED = override_settings(
    CONECTO_API_KEY=TOKEN, CONECTO_WEBHOOK_TOKEN=TOKEN, CONECTO_URLS=URLS
)


class FakeResponse:
    def __init__(self, status_code=200, payload=None, text=""):
        self.status_code = status_code
        self._payload = payload if payload is not None else {}
        self.text = text
        self.ok = 200 <= status_code < 300

    def json(self):
        return self._payload


class StaffCodeApiTests(TestCase):
    """The form's rules, enforced where they cannot be bypassed."""

    def setUp(self):
        self.client = APIClient()
        self.admin = User.objects.create_user(
            username="boss", password="x", role="admin", is_staff=True,
            allowed_sections=ALL_SECTIONS,
        )
        self.client.force_authenticate(self.admin)

    def _post(self, **overrides):
        body = {
            "username": "fanie",
            "staff_code": "TST-A",
            "first_name": "Fanie",
            "last_name": "Botha",
            "email": "fanie@skybre.co.za",
            "role": "technician",
        }
        body.update(overrides)
        return self.client.post("/api/staff-accounts/", body, format="json")

    def test_a_typed_code_is_the_one_used(self):
        response = self._post()

        self.assertEqual(response.status_code, 201, response.data)
        self.assertEqual(User.objects.get(username="fanie").staff_code, "TST-A")

    def test_creating_without_a_code_is_refused(self):
        response = self._post(staff_code="")

        self.assertEqual(response.status_code, 400)
        self.assertIn("staff_code", response.data)
        self.assertFalse(User.objects.filter(username="fanie").exists())

    def test_a_code_is_normalised_before_it_is_stored(self):
        """Compared, never read for meaning. Two spellings of one code is
        how a staff member ends up unable to register with nothing on
        screen to explain it."""
        response = self._post(staff_code="  tst-a  ")

        self.assertEqual(response.status_code, 201, response.data)
        self.assertEqual(User.objects.get(username="fanie").staff_code, "TST-A")

    def test_a_duplicate_code_is_refused_with_a_message(self):
        """The database's unique constraint would catch this too, as a 500
        from an IntegrityError. This is the same refusal, somewhere the
        admin can read it."""
        self._post()

        response = self._post(username="zandre", staff_code="TST-A")

        self.assertEqual(response.status_code, 400)
        self.assertIn("staff_code", response.data)

    def test_the_same_code_in_another_case_is_still_a_duplicate(self):
        self._post()

        response = self._post(username="zandre", staff_code="tst-a")

        self.assertEqual(response.status_code, 400)

    def test_suspending_an_account_does_not_need_the_code_resent(self):
        """The Users screen patches is_active on its own when somebody
        clicks Suspend. Requiring staff_code on every PATCH would break
        that button."""
        self._post()
        user = User.objects.get(username="fanie")

        response = self.client.patch(
            f"/api/staff-accounts/{user.pk}/", {"is_active": False}, format="json"
        )

        self.assertEqual(response.status_code, 200, response.data)
        user.refresh_from_db()
        self.assertFalse(user.is_active)
        self.assertEqual(user.staff_code, "TST-A")

    def test_a_code_clashing_with_a_generated_one_is_refused(self):
        """The generated namespace and the typed one share a column, so an
        admin can type a code the platform has already issued to somebody
        else. Refused, and said out loud -- silently accepting it would
        give two staff members one identity at Conecto."""
        existing = User.objects.create_user(
            username="shell", password="x", role="support",
        )

        response = self._post(username="clash", staff_code=existing.staff_code)

        self.assertEqual(response.status_code, 400)
        self.assertIn("staff_code", response.data)

    def test_code_created_outside_the_form_is_still_generated(self):
        """createsuperuser, management commands and the test suite all make
        staff accounts without going near this form. None of them should
        start failing because a form field became mandatory."""
        user = User.objects.create_user(username="shell", password="x", role="support")

        self.assertTrue(user.staff_code)


@CONFIGURED
class CodeChangeTests(TestCase):
    """Changing a code: revoke the old, register the new, in that order."""

    def setUp(self):
        self.client = APIClient()
        self.admin = User.objects.create_user(
            username="boss", password="x", role="admin", is_staff=True,
            allowed_sections=ALL_SECTIONS,
        )
        self.client.force_authenticate(self.admin)
        self.user = User.objects.create_user(
            username="fanie", password="x", role="technician",
        )
        User.objects.filter(pk=self.user.pk).update(staff_code="TST-A")
        self.user.refresh_from_db()

    def _sent(self, request):
        return [call.kwargs["json"] for call in request.call_args_list]

    def test_changing_a_code_revokes_the_old_one_first(self):
        with patch("conecto.client.requests.request") as request:
            request.return_value = FakeResponse(200, {"success": True})
            with self.captureOnCommitCallbacks(execute=True):
                self.user.staff_code = "TST-B"
                self.user.save()

        sent = self._sent(request)
        self.assertEqual(len(sent), 2)

        revocation, registration = sent
        self.assertEqual(revocation["staff_code"], "TST-A")
        self.assertFalse(revocation["is_active"])
        self.assertEqual(registration["staff_code"], "TST-B")
        self.assertTrue(registration["is_active"])

    def test_the_revocation_is_recorded_against_the_old_code(self):
        """So a failed revocation can be found and replayed. A live code at
        Conecto that nothing here refers to is how somebody keeps access
        after they should not have it."""
        with patch("conecto.client.requests.request") as request:
            request.return_value = FakeResponse(200, {"success": True})
            with self.captureOnCommitCallbacks(execute=True):
                self.user.staff_code = "TST-B"
                self.user.save()

        refs = set(
            ConectoCall.objects.filter(endpoint="registerStaffCode")
            .values_list("subject_ref", flat=True)
        )
        self.assertIn("TST-A", refs)
        self.assertIn("TST-B", refs)

    def test_a_failed_revocation_survives_as_a_replayable_row(self):
        with patch("conecto.client.requests.request") as request:
            request.return_value = FakeResponse(500, text="upstream error")
            with self.captureOnCommitCallbacks(execute=True):
                self.user.staff_code = "TST-B"
                self.user.save()

        row = ConectoCall.objects.get(
            endpoint="registerStaffCode", subject_ref="TST-A",
        )
        self.assertEqual(row.status, ConectoCall.Status.FAILED)

    def test_saving_without_changing_the_code_revokes_nothing(self):
        """A role change, a phone number, a password reset. Revoking on any
        of those would cut off a working app account for no reason."""
        with patch("conecto.client.requests.request") as request:
            request.return_value = FakeResponse(200, {"success": True})
            with self.captureOnCommitCallbacks(execute=True):
                self.user.role = "support"
                self.user.save()

        sent = self._sent(request)
        self.assertEqual(len(sent), 1)
        self.assertEqual(sent[0]["staff_code"], "TST-A")
        self.assertTrue(sent[0]["is_active"])

    def test_changing_a_code_through_the_api_does_the_same(self):
        with patch("conecto.client.requests.request") as request:
            request.return_value = FakeResponse(200, {"success": True})
            with self.captureOnCommitCallbacks(execute=True):
                response = self.client.patch(
                    f"/api/staff-accounts/{self.user.pk}/",
                    {"staff_code": "TST-B"}, format="json",
                )

        self.assertEqual(response.status_code, 200, response.data)
        sent = self._sent(request)
        self.assertEqual(len(sent), 2)
        self.assertEqual(sent[0]["staff_code"], "TST-A")
        self.assertFalse(sent[0]["is_active"])
